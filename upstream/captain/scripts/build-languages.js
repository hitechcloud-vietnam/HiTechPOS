const fs = require('node:fs');
const path = require('node:path');
const dir = path.join(__dirname, '../assets/common/locales');
const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
function bundle() {
  return '/* Generated by scripts/build-languages.js from the offline language catalogs. */\n(function(root){\nroot.CAPTAIN_LANGUAGES=' + JSON.stringify(manifest) + ';\n' + manifest.filter(l=>l.code!=='en').map(l=>'root.I18N.register('+JSON.stringify(l.code)+','+JSON.stringify(JSON.parse(fs.readFileSync(path.join(dir,l.code+'.json'),'utf8')))+');').join('\n')+'\n})(window);\n';
}
if (require.main === module) {
  const target=path.join(dir, '../languages.js'), content=bundle();
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) fs.writeFileSync(target, content);
}
module.exports = { bundle };
