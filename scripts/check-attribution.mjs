import fs from "node:fs";
import path from "node:path";
const forbidden =
  /co-authored-by:.*(?:assistant|agent|bot|gpt|claude|codex)|generated by (?:chatgpt|codex|claude|copilot)/i;
const skip = new Set([
  ".git",
  "node_modules",
  ".expo",
  "dist",
  "android",
  "ios",
  "test-results",
]);
let failures = 0;
function visit(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (skip.has(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) visit(p);
    else if (
      /\.(md|json|ts|tsx|yml|yaml)$/.test(p) &&
      forbidden.test(fs.readFileSync(p, "utf8"))
    ) {
      console.error(p);
      failures++;
    }
  }
}
visit(process.cwd());
if (failures) process.exitCode = 1;
else console.log("Attribution check passed.");
